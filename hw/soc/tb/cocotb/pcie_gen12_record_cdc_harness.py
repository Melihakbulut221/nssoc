"""Independent public-port queues; no DUT internal signals or FIFO pointers."""
from collections import deque
from pathlib import Path
import os
import random
import sys
import cocotb
from cocotb.triggers import Timer
ROOT=Path(__file__).resolve().parents[4]
sys.path.insert(0,str(ROOT/'scripts'))
import check_pcie_gen12_raw32_rx as table_rx

FIELDS=('data','k','code_error','disparity_error','comma')
WIDTHS=(128,16,16,16,16)
DEPTH=int(os.environ.get('CDC_DEPTH','32'))
MASK=(1<<192)-1

def split(value):
    result=[]
    for width in WIDTHS:
        result.append(value&((1<<width)-1));value>>=width
    assert value==0
    return tuple(result)

def pack(symbols):
    assert len(symbols)==16
    return tuple(sum(s[column]<<(slot*(8 if column==0 else 1))
                     for slot,s in enumerate(symbols)) for column in range(5))

def records(seed,count):
    rng=random.Random(seed)
    return [split(rng.getrandbits(192)) for _ in range(count)]

def stream_words(offset=0,polarity=0,initial_rd=0,count=64,random_codes=False):
    """Independent standard-table encodings, then global wire-bit coordinates.
    Every record begins with COM. Internal COM/error codes remain ordinary slots.
    Invalid raw code values are deliberately not generated by the DUT encoder.
    """
    table=__import__('json').loads((ROOT/'sw/tests/data/pcie_gen12_ieee8023z_codes.json').read_text())
    enc={(rd,r['k'],r['data']):int(r[key][::-1],2)
         for r in table['rows'] for rd,key in enumerate(('minus','plus'))}
    rng=random.Random(0xCDC12+offset+count+polarity)
    bits=[0]*offset;rd=initial_rd
    for record in range(count):
        for slot in range(16):
            if slot==0 or (slot==7 and record%4==0):
                code=enc[rd,1,188]
            elif random_codes:
                # All 1024 received patterns recur at every non-COM position.
                code=(record*17+slot*67)%1024
            else:
                code=enc[rd,0,rng.randrange(256)]
            bits.extend((code>>i)&1 for i in range(10))
            rd=table_rx.rx_rd(code,rd)
    # A whole-number multiple of records leaves only the offset residue.
    # Zero padding cannot add a complete further candidate.
    bits.extend([0]*((-len(bits))%32))
    words=[sum(b<<i for i,b in enumerate(bits[start:start+32])) for start in range(0,len(bits),32)]
    return [w^(0xffffffff if polarity else 0) for w in words]

class Link:
    def __init__(self,d,composed=False,wr_ps=4000,rd_ps=4001,phase_ps=137):
        self.d=d;self.composed=composed
        self.wr_ps=wr_ps;self.rd_ps=rd_ps;self.phase_ps=phase_ps
        self.pending=deque();self.expected=deque();self.available=deque();self.partial=[]
        self.ready=True;self.loss=False;self.polarity=0;self.allow_fault=False
        self.pause_wr=False;self.pause_rd=False;self.gap=1;self.gap_left=0
        self.error=None;self.tasks=[];self.held=None
        self.writes=0;self.reads=0;self.words=0;self.completed=0
        self.field_seen=[set() for _ in FIELDS];self.positions=[set()for _ in range(4)]
        self.wr_cycles=0;self.rd_cycles=0
        self.oracle=table_rx.SerialOracle(*table_rx.table()) if composed else None
        self.names=dict(por='por_ni',wc='wr_clk_i',rc='rd_clk_i',wr='wr_reset_i',rr='rd_reset_i',
                        wi='wr_valid_i',lo='wr_loss_i',wa='wr_accept_o',wf='wr_fault_o',wo='wr_overflow_o',
                        wn='wr_running_o',rn='rd_running_o',rf='rd_fault_o',rv='rd_valid_o',ready='rd_ready_i')
        if composed:
            self.names.update(wc='recovered_clk_i',rc='common_clk_i',wr='recovered_reset_i',
                              rr='common_reset_i',wi='raw_valid_i',lo='loss_i',wa='recovered_accept_o',
                              wf='recovered_fault_o',wo='recovered_overflow_o',wn='recovered_running_o',
                              rn='common_running_o',rf='common_fault_o',rv='record_valid_o',ready='record_ready_i')
    def sig(self,name):return getattr(self.d,self.names.get(name,name))
    def value(self,name):return int(self.sig(name).value)
    def reset_asserted(self):return not self.value('por') or self.value('wr') or self.value('rr')
    def output(self):
        prefix='record_' if self.composed else 'rd_'
        return tuple(int(getattr(self.d,prefix+n+'_o').value)for n in FIELDS)
    async def start(self,polarity=0):
        self.polarity=polarity
        for name in ('por','wc','rc','wr','rr','wi','lo','ready'):self.sig(name).value=0
        if self.composed:
            self.d.raw_i.value=0;self.d.polarity_i.value=polarity
        else:
            for name in FIELDS:getattr(self.d,'wr_'+name+'_i').value=0
        await Timer(1,unit='ps')
        self.tasks=[cocotb.start_soon(self.writer()),cocotb.start_soon(self.reader())]
        await Timer(50000,unit='ps');self.sig('por').value=1
        await self.until(lambda:self.value('wn') and self.value('rn'))
    async def until(self,condition,limit=30000):
        for _ in range(limit):
            if self.error:raise self.error
            if condition():return
            await Timer(1000,unit='ps')
        raise AssertionError('bounded public-port scenario timeout')
    def observe_symbols(self,batch):
        data,k,ce,de,co,count,*_=batch
        for slot in range(count):
            sym=((data>>(8*slot))&255,(k>>slot)&1,(ce>>slot)&1,(de>>slot)&1,(co>>slot)&1)
            if self.partial or (sym[0]==188 and sym[1] and not sym[2] and sym[4]):
                at=len(self.partial)
                for field in range(4):
                    if sym[field+1]:self.positions[field].add(at)
                self.partial.append(sym)
                if len(self.partial)==16:
                    self.available.append(pack(self.partial));self.partial=[];self.completed+=1
    async def writer(self):
        try:
            while True:
                self.sig('wc').value=0
                if self.pause_wr:
                    self.sig('lo').value=int(self.loss)
                    if self.composed:self.d.polarity_i.value=self.polarity
                    await Timer(100,unit='ps');continue
                live=not self.reset_asserted() and self.value('wn')
                item=self.pending[0] if live and self.pending and not self.gap_left else None
                self.sig('wi').value=int(item is not None);self.sig('lo').value=int(self.loss)
                if self.composed:
                    self.d.polarity_i.value=self.polarity
                    self.d.raw_i.value=item if item is not None else 0
                elif item is not None:
                    for field,val in zip(FIELDS,item):getattr(self.d,'wr_'+field+'_i').value=val
                await Timer(self.wr_ps//2,unit='ps')
                active=not self.reset_asserted() and self.value('wn')
                accepted=self.value('wa')
                if self.composed and active:
                    self.observe_symbols(self.oracle.step(1,1,0,self.polarity,int(item is not None),item or 0))
                elif self.composed:
                    self.oracle.clear();self.oracle.prev=self.polarity
                if accepted:
                    assert active and not self.loss,'accepted outside source epoch'
                    if self.composed:
                        assert self.available,'accepted record before oracle completed it'
                        value=self.available.popleft()
                    else:
                        assert item is not None,'fabricated write acceptance'
                        value=item
                    self.expected.append(value);self.writes+=1
                if active and item is not None:
                    if not self.composed and not self.allow_fault:assert accepted,'unexpected live record rejection'
                    self.pending.popleft();self.gap_left=self.gap-1
                    self.words+=int(self.composed)
                elif self.gap_left:self.gap_left-=1
                self.sig('wc').value=1;self.wr_cycles+=1
                await Timer(self.wr_ps-self.wr_ps//2,unit='ps')
                if not self.allow_fault and not self.reset_asserted():
                    assert not self.value('wf'),'unexpected source fault'
        except Exception as error:
            self.error=error;raise
    async def reader(self):
        await Timer(self.phase_ps,unit='ps')
        try:
            while True:
                self.sig('rc').value=0
                if self.pause_rd:
                    await Timer(100,unit='ps');continue
                self.sig('ready').value=int(self.ready)
                await Timer(self.rd_ps//2,unit='ps')
                valid=self.value('rv');running=self.value('rn');ready=self.value('ready')
                item=self.output()
                if self.reset_asserted() or not running:
                    assert not valid and item==(0,)*5,'output escaped epoch barrier'
                    self.held=None
                else:
                    if self.held is not None:
                        assert valid and item==self.held,'held complete record changed'
                    if not valid:assert item==(0,)*5,'invalid fields not masked'
                    self.held=item if valid and not ready else None
                    if valid and ready:
                        assert self.expected,'fabricated/duplicate/unaccepted record'
                        assert item==self.expected.popleft(),'field or order mismatch'
                        self.reads+=1
                        for seen,val in zip(self.field_seen,item):seen.add(val)
                self.sig('rc').value=1;self.rd_cycles+=1
                await Timer(self.rd_ps-self.rd_ps//2,unit='ps')
        except Exception as error:
            self.error=error;raise
    async def feed(self,items,gap=1):
        self.gap=gap;self.pending.extend(items)
        await self.until(lambda:not self.pending,limit=max(30000,len(items)*gap*self.wr_ps//1000+1000))
    async def drain(self):
        self.ready=True
        # Includes decoder/collector/prefetch latency after the last raw input.
        await Timer(100000,unit='ps')
        await self.until(lambda:not self.pending and not self.expected and not self.available)
        await Timer(50000,unit='ps')
        assert not self.value('rv'),'late duplicate'
        if self.error:raise self.error
    async def reset(self,domain='wr',stopped=None,polarity=None,prefill=()):
        self.sig(domain).value=1
        self.pending.clear();self.pending.extend(prefill)
        self.expected.clear();self.available.clear();self.partial=[]
        self.held=None;self.loss=False;self.gap_left=0
        if polarity is not None:self.polarity=polarity
        if self.oracle:self.oracle.clear();self.oracle.prev=self.polarity
        await Timer(1100,unit='ps')
        assert not self.value('rv') and not self.value('wa')
        assert self.output()==(0,)*5
        self.pause_wr=stopped=='wr';self.pause_rd=stopped=='rd'
        await Timer(50000,unit='ps');self.sig(domain).value=0
        if stopped:
            await Timer(100000,unit='ps')
            assert not self.value('wn') and not self.value('rn'),'stopped-clock startup barrier bypass'
            self.pause_wr=self.pause_rd=False
        await self.until(lambda:self.value('wn') and self.value('rn'))
        self.allow_fault=False
        assert not self.value('wf') and not self.value('rf')
    async def fault_visible(self,overflow):
        await self.until(lambda:self.value('wf'))
        assert bool(self.value('wo'))==overflow
        await self.until(lambda:self.value('rf'))
        reads=self.reads;self.ready=True
        await Timer(80000,unit='ps')
        assert self.reads==reads and not self.value('rv') and not self.value('wn')
        assert self.output()==(0,)*5
    def close(self):
        for task in self.tasks:task.cancel()
