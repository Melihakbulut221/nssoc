"""Prepare a sizing-feasibility probe on a routed main-chip database.

Restores the verified post-route input package (as mainchip_sta_measure does),
then writes probe.tcl for the routing engine's OpenROAD: slow-corner libraries
and the unchanged physical SDC with the resolved configuration as ::env, the
configured don't-use cells, placement-estimated parasitics, then repair_design
and an unbounded repair_timing -setup with WNS reported before and after.
It measures whether sizing and buffering alone can reach the original clocks;
the database it writes is an experiment, not a candidate.
"""
import json,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent))
import mainchip_sta_measure as m
CORNER='nom_slow_1p08V_125C'
def tcl_value(v):
    if isinstance(v,bool):return '1'if v else '0'
    if isinstance(v,(int,float)):return repr(float(v))if isinstance(v,float)else str(v)
    if isinstance(v,str):return v
    if isinstance(v,list)and all(isinstance(x,(str,int,float))for x in v):return ' '.join(str(x)for x in v)
    return None
def brace(s):return '{'+s.replace('\\','\\\\').replace('{','\\{').replace('}','\\}')+'}'
def main(package,odb,out,stage):
    package,out=Path(package),Path(out);out.mkdir(parents=True,exist_ok=True)
    m.restore(package)
    cfg=json.loads((package/'resolved-flow-config.json').read_text())
    env=[]
    for k,v in sorted(cfg.items()):
        t=tcl_value(v)
        if t is not None:env.append(f'set ::env({k}) {brace(t)}')
    libs=cfg['LIB'][CORNER] if isinstance(cfg.get('LIB'),dict)and CORNER in cfg['LIB'] else None
    if libs is None:
        libs=[l for k,v in cfg['LIB'].items()if __import__('fnmatch').fnmatch(CORNER,k)for l in v]
    extra=[]
    for key in('EXTRA_LIBS','PAD_LIBS'):
        v=cfg.get(key)
        if isinstance(v,list):extra+=v
        elif isinstance(v,dict):extra+=[l for k,ls in v.items()if __import__('fnmatch').fnmatch(CORNER,k)for l in ls]
    macros=[]
    for name,mac in(cfg.get('MACROS')or{}).items():
        for k,ls in(mac.get('lib')or{}).items():
            if __import__('fnmatch').fnmatch(CORNER,k):macros+=ls
    sdc=cfg.get('SIGNOFF_SDC_FILE')or cfg['PNR_SDC_FILE']
    dont=cfg.get('DONT_USE_CELLS')or[]
    t=['# generated by mainchip_sizing_probe.py']+env+[f'read_db {odb}']
    t+=[f'read_liberty {l}'for l in list(dict.fromkeys(libs+extra+macros))]
    t+=[f'read_sdc {sdc}','set_propagated_clock [all_clocks]']
    # LibreLane's set_rc.tcl lives in its AppImage; use the configured wire-RC layers directly.
    def layers(key,default):
        v=cfg.get(key);return v if isinstance(v,list)and v else default
    t+=['set_wire_rc -signal -layers {'+' '.join(layers('SIGNAL_WIRE_RC_LAYERS',['Metal2','Metal3']))+'}',
        'set_wire_rc -clock -layers {'+' '.join(layers('CLOCK_WIRE_RC_LAYERS',['Metal4','Metal5']))+'}']
    if dont:t.append('set_dont_use [get_lib_cells {'+' '.join(dont)+'}]')
    t+=['estimate_parasitics -placement',
        'puts "NSSOC_PROBE before wns=[sta::worst_slack -max] tns=[sta::total_negative_slack -max] hold=[sta::worst_slack -min]"',
        'puts "NSSOC_PROBE before slew=[sta::max_slew_violation_count] cap=[sta::max_capacitance_violation_count] fanout=[sta::max_fanout_violation_count]"',
        'report_checks -path_delay max -group_path_count 1 -digits 3 -format end',
        'repair_design -verbose',
        'estimate_parasitics -placement',
        'puts "NSSOC_PROBE after_design wns=[sta::worst_slack -max] tns=[sta::total_negative_slack -max] slew=[sta::max_slew_violation_count] cap=[sta::max_capacitance_violation_count] fanout=[sta::max_fanout_violation_count]"']
    if stage=='timing':
        t+=['repair_timing -setup -verbose -repair_tns 100',
            'estimate_parasitics -placement',
            'puts "NSSOC_PROBE after_timing wns=[sta::worst_slack -max] tns=[sta::total_negative_slack -max] hold=[sta::worst_slack -min]"',
            'report_checks -path_delay max -group_path_count 1 -digits 3']
    t+=['puts "NSSOC_PROBE insts=[llength [[ord::get_db_block] getInsts]]"']
    (out/'probe.tcl').write_text('\n'.join(t)+'\n')
    (out/'probe-inputs.json').write_text(json.dumps(dict(libs=libs,extra=extra,macros=macros,sdc=sdc,dont_use=dont,signal_rc=cfg.get('SIGNAL_WIRE_RC_LAYERS'),clock_rc=cfg.get('CLOCK_WIRE_RC_LAYERS')),indent=1))
    print({k:v for k,v in cfg.items()if any(x in k for x in('RC','DONT','LAYER','DRIV','MAX_','FANOUT','TRANSITION'))and len(str(v))<300})
    print(json.dumps(dict(libs=len(libs),extra=len(extra),macros=len(macros),sdc=sdc,dont_use=len(dont),scripts_dir=cfg.get('SCRIPTS_DIR'))))
if __name__=='__main__':main(*sys.argv[1:5])
