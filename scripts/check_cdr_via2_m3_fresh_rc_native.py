def source_guard():
    e=os.environ;n.require(e.get('GITHUB_ACTIONS')=='true'and e.get('RUNNER_ENVIRONMENT')=='github-hosted'and e.get('GITHUB_JOB')=='source-controls','hosted source job')
    n.require(e.get('GITHUB_REPOSITORY')=='Melihakbulut221/nssoc'and e.get('GITHUB_EVENT_NAME')=='workflow_dispatch'and e.get('GITHUB_REF')=='refs/heads/'+BRANCH,'exact manual source branch')
    n.require(e.get('GITHUB_RUN_ATTEMPT')=='1'and e.get('APPROVED_SOURCE')==e.get('GITHUB_SHA'),'exact approved source')
    head=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip();n.require(head==e['GITHUB_SHA'],'actual checkout')
    raw=n.core.regular(ROOT,MANIFEST).read_bytes();n.require(raw==subprocess.check_output(['git','show',head+':'+MANIFEST],cwd=ROOT),'immutable source manifest')
    m=n.read(ROOT/MANIFEST);n.require(m['native_authority']is False,'source-only manifest')
    for path,pin in m['files'].items():
        actual=n.pin(n.core.regular(ROOT,path));n.require(actual['sha256']==pin['sha256']and('bytes'not in pin or actual['bytes']==pin['bytes']),'protected source '+path)
    return dict(source=head,run_id=int(e['GITHUB_RUN_ID']),attempt=1)

